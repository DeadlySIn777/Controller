"""Generate C headers from spec/protocol.json (IS-1) and the codec's golden vectors.

    python gateware/v3/tools/gen_c_layout.py            # write cnc3_layout.h, cnc3_rules.h and cnc3_vectors.h
    python gateware/v3/tools/gen_c_layout.py --check    # fail if either header is out of date

The layout header carries every frame's field offsets and sizes, the opcode table with its
chip-select assignment, and the reserved/zero byte ranges that receivers must check. The C
codec (cnc3/src/cnc3_proto.c) uses only these macros for positions, so a spec revision that
moves a field changes the C build rather than silently disagreeing with it.
"""
import argparse
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
_spec = importlib.util.spec_from_file_location("protocol_v3", os.path.join(HERE, "protocol_v3.py"))
p3 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(p3)

LAYOUT_H = os.path.join(ROOT, "cnc3", "src", "cnc3_layout.h")
VECTORS_H = os.path.join(ROOT, "cnc3", "tests", "cnc3_vectors.h")
RULES_H = os.path.join(ROOT, "cnc3", "src", "cnc3_rules.h")


def ident(text):
    return re.sub(r"[^A-Za-z0-9]", "_", text).upper()


def layout_header():
    s = p3.spec()
    out = ["/* SPDX-License-Identifier: LicenseRef-Proprietary */",
           f"/* GENERATED by gateware/v3/tools/gen_c_layout.py from spec/protocol.json ({s.revision}). Do not edit. */",
           "#ifndef CNC3_LAYOUT_H", "#define CNC3_LAYOUT_H", "",
           f'#define CNC3_SPEC_REVISION "{s.revision}"',
           f"#define CNC3_CS_FB_BYTES {s.cs_frame_bytes['CS_FB']}",
           f"#define CNC3_CS_CMD_BYTES {s.cs_frame_bytes['CS_CMD']}",
           f"#define CNC3_PAYLOAD_OFF {s.payload_offset}",
           f"#define CNC3_PAYLOAD_SIZE {s.payload_size}", ""]
    for code, op in sorted(s.opcodes.items()):
        out.append(f"#define CNC3_OP_{ident(op['name'])} 0x{code:02X}")
    for cs in ("CS_FB", "CS_CMD"):
        bits = 0
        for code in s.cs_opcodes[cs]:
            bits |= 1 << code
        out.append(f"#define CNC3_{cs}_OPCODES 0x{bits:08X}u /* bit n set = opcode n valid on {cs} */")
    out.append("")
    for name, layout in s.layouts.items():
        prefix = "CNC3_" + ident(name)
        out.append(f"/* {name}: {layout.length} bytes */")
        out.append(f"#define {prefix}_LEN {layout.length}")
        zero_index = 0
        zeros = []
        names = [f.name for f in layout.fields]
        for f in layout.fields:
            if f.must_be_zero:
                zeros.append(f)
            if names.count(f.name) > 1:
                fname = f"{ident(f.name)}{zero_index}"
                zero_index += 1
            else:
                fname = ident(f.name)
            out.append(f"#define {prefix}_{fname}_OFF {f.offset}")
            out.append(f"#define {prefix}_{fname}_SIZE {f.size}")
        ranges = ", ".join(f"{{{f.offset}, {f.size}}}" for f in zeros) or "{0, 0}"
        out.append(f"#define {prefix}_ZERO_COUNT {len(zeros)}")
        out.append(f"#define {prefix}_ZERO_RANGES {{{ranges}}}")
        out.append("")
    out += ["#endif", ""]
    return "\n".join(out)


RULE_LAYOUTS = ("fb_command", "cmd_command", "fb_read_payload_at_16", "configure_payload_at_16",
                "configure_io_page0_at_16", "configure_io_page1_at_16", "configure_io_card_pages_at_16",
                "iol1_command")
HEADER_FIELDS = ("magic", "abi", "opcode", "channel_mask", "crc16", "crc32c", "sof", "version", "expected_slot",
                 "epoch", "control")
ELEM = {"u8": (1, 0), "u16": (2, 0), "u24": (3, 0), "u32": (4, 0), "s16": (2, 1), "s32": (4, 1)}


def rules_header():
    """Static rule tables for cnc3_proto.c, derived by protocol_v3 from the spec's rule phrases."""
    s = p3.spec()
    opcode_bits = {op["name"]: code for code, op in s.opcodes.items()}
    index = {name: i for i, name in enumerate(RULE_LAYOUTS)}
    out = ["/* SPDX-License-Identifier: LicenseRef-Proprietary */",
           f"/* GENERATED by gateware/v3/tools/gen_c_layout.py from spec/protocol.json ({s.revision}). Do not edit. */",
           "/* Included only by cnc3_proto.c. */", "#ifndef CNC3_RULES_H", "#define CNC3_RULES_H",
           '#include "cnc3_proto_types.h"', ""]
    for name in RULE_LAYOUTS:
        layout = s.layout(name)
        rows = []
        for f in layout.fields:
            r = f.rules
            if f.count is not None:
                esize, signed = ELEM[f.elem]
                count = f.count
            elif f.type in ELEM:
                esize, signed = ELEM[f.type]
                count = 1
            else:
                esize, signed, count = 0, 0, 1  # bytes/ascii: only the zero rule applies
            ranges = r.get("allowed", [])
            if len(ranges) > 4:
                raise SystemExit(f"{name}.{f.name}: more than 4 allowed ranges")
            rng = ", ".join(f"{{{lo}u, {hi}u}}" for lo, hi in ranges) or "{0u, 0u}"
            only = 0
            for op in r.get("only_opcodes", ()):
                only |= 1 << opcode_bits[op]
            relation, rel_off, rel_size, rel_bits, rel_value = 0, 0, 0, 0, 0
            if "disjoint_with" in r:
                other = layout.field(r["disjoint_with"])
                relation, rel_off, rel_size = 1, other.offset, other.size
            elif "subset_of" in r:
                other = layout.field(r["subset_of"])
                relation, rel_off, rel_size = 2, other.offset, other.size
            elif "bits_require" in r:
                bits, other_name, need = r["bits_require"]
                other = layout.field(other_name)
                relation = 3 if need == "nonzero" else 4
                rel_off, rel_size, rel_bits = other.offset, other.size, bits
                rel_value = 0 if need == "nonzero" else need
            if not r or f.name in HEADER_FIELDS:
                continue  # header fields are checked explicitly, in the codec's fixed order
            rows.append(f'  {{"{f.name}", {f.offset}, {f.size}, {count}, {esize}, {signed}, {int(bool(r.get("zero")))}, '
                        f'{int(bool(r.get("nonzero")))}, {len(ranges)}, {{{rng}}}, 0x{r.get("zero_bits", 0):X}u, '
                        f'0x{only:X}u, {relation}, {rel_off}, {rel_size}, 0x{rel_bits:X}u, {rel_value}u}},')
        out.append(f"static const struct cnc3_field_rule cnc3_rules_{name}[] = {{")
        out += rows or ['  {"none", 0, 0, 0, 0, 0, 0, 0, 0, {{0u, 0u}}, 0u, 0u, 0, 0, 0, 0u, 0u},']
        out.append("};")
    out.append("static const struct cnc3_layout_rules cnc3_layouts[] = {")
    for name in RULE_LAYOUTS:
        out.append(f'  {{"{name}", {s.layout(name).length}, sizeof cnc3_rules_{name} / sizeof cnc3_rules_{name}[0], '
                   f"cnc3_rules_{name}}},")
    out.append("};")
    for name in RULE_LAYOUTS:
        out.append(f"#define CNC3_LAYOUT_{ident(name)} {index[name]}")
    out.append("static const struct cnc3_opcode_rule cnc3_opcode_rules[] = {")
    seq_code = {None: 0, "zero": 1, "nonzero": 2}
    for code, op in sorted(s.opcodes.items()):
        r = s.opcode_rules[code]
        zr = r["zero_ranges"]
        if len(zr) > 2:
            raise SystemExit(f"{op['name']}: more than 2 zero ranges")
        zrs = ", ".join(f"{{{lo}, {hi}}}" for lo, hi in zr) or "{0, 0}"
        b16 = r["byte16"] or []
        b16s = ", ".join(f"{{{lo}u, {hi}u}}" for lo, hi in b16) or "{0u, 0u}"
        emb = r["embedded_iol1"] or (0, 0, 0)
        payload = index[r["payload_layout"]] if r["payload_layout"] else -1
        pages = [index[n] for n in r["payload_pages"]]
        pgs = ", ".join(str(i) for i in pages) or "0"
        out.append(f'  {{"{op["name"]}", 0x{code:02X}, {0 if op["cs"] == "CS_FB" else 1}, {seq_code[r["sequence"]]}, '
                   f'{int(r["session_nonzero"])}, {int(r["paired"])}, {int(r["mask_zero"])}, {int(r["mask_nonzero"])}, '
                   f'{int(r["rest_zero"])}, {len(zr)}, {{{zrs}}}, {len(b16)}, {{{b16s}}}, '
                   f'{int(bool(r["embedded_iol1"]))}, {emb[0]}, {emb[1]}, {emb[2]}, {payload}, {len(pages)}, {{{pgs}}}}},')
    out += ["};", "#define CNC3_OPCODE_RULE_COUNT (sizeof cnc3_opcode_rules / sizeof cnc3_opcode_rules[0])",
            "#endif", ""]
    return "\n".join(out)


