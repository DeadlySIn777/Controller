def vectors_header():
    vectors = p3.golden_vectors()
    codes = sorted({v["expect"] for v in vectors["vectors"]})
    out = ["/* SPDX-License-Identifier: LicenseRef-Proprietary */",
           "/* GENERATED by gateware/v3/tools/gen_c_layout.py from protocol_v3.golden_vectors(). Do not edit. */",
           "#ifndef CNC3_VECTORS_H", "#define CNC3_VECTORS_H", "#include <stddef.h>", "#include <stdint.h>",
           "struct cnc3_vector { const char *name; const char *chip_select; const char *expect; size_t length; const uint8_t *data; };"]
    for i, v in enumerate(vectors["vectors"]):
        data = bytes.fromhex(v["hex"])
        body = ",".join(f"0x{b:02X}" for b in data)
        out.append(f"static const uint8_t cnc3_vector_{i}[{len(data)}] = {{{body}}};")
    out.append("static const struct cnc3_vector cnc3_vectors[] = {")
    for i, v in enumerate(vectors["vectors"]):
        out.append(f'  {{"{v["name"]}", "{v["chip_select"]}", "{v["expect"]}", sizeof cnc3_vector_{i}, cnc3_vector_{i}}},')
    out.append("};")
    for name, cs, values in RESPONSE_REFERENCES:
        data = p3.encode_response(cs, values)
        body = ",".join(f"0x{b:02X}" for b in data)
        out.append(f"static const uint8_t cnc3_{name}[{len(data)}] = {{{body}}};")
    out += [f"#define CNC3_VECTOR_COUNT {len(vectors['vectors'])}",
            "/* Expected results: " + ", ".join(codes) + " */", "#endif", ""]
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, text in ((LAYOUT_H, layout_header()), (RULES_H, rules_header()), (VECTORS_H, vectors_header())):
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if args.check:
            if current != text:
                stale.append(os.path.relpath(path, ROOT))
        elif current != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("stale generated headers:", ", ".join(stale))
        return 1
    if args.check:
        print("generated headers current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
